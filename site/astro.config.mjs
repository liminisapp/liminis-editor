// @ts-check
import { defineConfig } from 'astro/config'
import starlight from '@astrojs/starlight'
import react from '@astrojs/react'
import { unified } from '@astrojs/markdown-remark'
import { fileURLToPath } from 'node:url'
import { remarkC4 } from '@liminis/diagrams/remark'

// Served as a GitHub Pages project site under the org's custom domain, so this
// resolves to https://docs.liminis.app/liminis-editor/ — the subpath is the
// same whichever host serves it.
//
// The demo is a separate Vite app, built with its own base and copied into this
// site's public/ by scripts/stage-demo.mjs. Nothing here builds it and Astro
// cannot see inside it, so links to it are external as far as any link checker
// is concerned.
export default defineConfig({
  // `@site` so the import remarkC4 injects resolves from any page depth. The
  // plugin defaults to this alias; it lives in @liminis/diagrams/remark now.
  vite: {
    resolve: {
      alias: { '@site': fileURLToPath(new URL('./src', import.meta.url)) },
    },
  },
  // Turns ```c4 fences into live islands. The source pages stay readable as
  // plain markdown on GitHub — and inside the published tarball, which ships
  // docs/ — where the fence renders as a code block beside its committed SVG.
  // See @liminis/diagrams/remark.
  //
  // Through the unified processor rather than a bare `markdown.remarkPlugins`:
  // Astro 7 made Sätteri the default Markdown processor and deprecated the bare
  // option (it still works today, with a build warning, and is slated for
  // removal). remarkC4 is a remark plugin, so it needs unified's pipeline.
  markdown: { processor: unified({ remarkPlugins: [remarkC4] }) },
  site: 'https://docs.liminis.app',
  base: '/liminis-editor',
  integrations: [
    react(),
    starlight({
      customCss: ['./src/styles/playground.css'],
      title: '@liminis/editor',
      description:
        'A Lexical-based markdown editor component: markdown in, markdown out, with annotations that survive editing.',
      social: [
        { icon: 'github', label: 'GitHub', href: 'https://github.com/liminisapp/liminis-editor' },
      ],
      // No site-wide editLink.baseUrl: Starlight builds that link from the
      // page's path relative to src/content/docs, which here is the generated
      // copy — gitignored, never committed, so every link would 404. Each page
      // carries its own `editUrl` instead, written by sync-docs.mjs from the
      // real file it came from.
      sidebar: [
        { label: 'Overview', link: '/' },
        {
          // The demo is a separate Vite app staged into this site's output, so
          // Astro cannot see it and it can never appear in an autogenerated
          // group. Without an explicit entry there is no path to it from any
          // page but the homepage — a live editor nobody can find.
          label: 'Demo',
          link: '/demo/',
          attrs: { target: '_self' },
        },
        {
          label: 'Guide',
          // Generated from ../docs by scripts/sync-docs.mjs, ordered by the
          // sidebar.order it writes into each page's frontmatter.
          items: [{ autogenerate: { directory: 'guide' } }],
        },
      ],
    }),
  ],
})
